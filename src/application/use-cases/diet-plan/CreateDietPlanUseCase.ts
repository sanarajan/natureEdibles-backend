import { inject, injectable } from 'tsyringe';
import { ICreateDietPlanUseCase } from '../../interfaces/use-cases/diet-plan/IDietPlanUseCases';
import { IDietPlanRepository } from '../../../domain/repositories/IDietPlanRepository';
import { IConsultationBookingRepository } from '../../../domain/repositories/IConsultationBookingRepository';
import { DietPlan, DietPlanSection, DietPlanDaySchedule } from '../../../domain/entities/DietPlan';
import { calculateSubscriptionEndDate, parseDateOnly } from '../../../domain/utils/subscriptionUtils';

@injectable()
export class CreateDietPlanUseCase implements ICreateDietPlanUseCase {
    constructor(
        @inject('IDietPlanRepository') private dietPlanRepo: IDietPlanRepository,
        @inject('IConsultationBookingRepository') private consultationRepo: IConsultationBookingRepository
    ) {}

    async execute(data: any, createdBy: string): Promise<DietPlan> {
        const consultation = await this.consultationRepo.findById(data.consultationId);
        if (!consultation) {
            throw new Error('Consultation not found');
        }

        if (consultation.status !== 'COMPLETED') {
            throw new Error('Consultation must be COMPLETED to create a Diet Plan');
        }

        if (consultation.userId !== data.customerId) {
            throw new Error('Customer ID mismatch');
        }

        const existingPlan = await this.dietPlanRepo.findByConsultationId(data.consultationId);
        if (existingPlan) {
            throw new Error('A Diet Plan already exists for this consultation');
        }

        if (!data.startDate) {
            throw new Error('Start date is required');
        }

        const startDate = parseDateOnly(data.startDate);

        // Subscription duration handling
        let durationMonths = data.durationMonths ? Number(data.durationMonths) : undefined;
        let durationType = data.durationType || 'months';
        let durationValue = data.durationValue ? Number(data.durationValue) : (durationMonths || 1);

        if (durationMonths) {
            if (![1, 2, 3, 6].includes(durationMonths)) {
                throw new Error('Subscription duration must be 1, 2, 3, or 6 months');
            }
            durationType = 'months';
            durationValue = durationMonths;
        } else if (!data.durationType || !['days', 'weeks', 'months'].includes(data.durationType)) {
            // Backward-compatible fallback
            throw new Error('Invalid duration type');
        }

        // Calculate subscription end date
        const endDate = durationMonths 
            ? calculateSubscriptionEndDate(startDate, durationMonths)
            : data.endDate ? parseDateOnly(data.endDate) : undefined;

        // Visibility date validation
        let visibilityDate = data.visibilityDate ? parseDateOnly(data.visibilityDate) : new Date(startDate);
        if (visibilityDate.getTime() > startDate.getTime()) {
            throw new Error('Plan visibility date cannot be after the subscription start date');
        }

        // Display mode validation
        const validDisplayModes = ['TODAY', 'CURRENT_WEEK', 'NEXT_7_DAYS'];
        const displayMode = validDisplayModes.includes(data.displayMode) ? data.displayMode : 'TODAY';
        const advanceDays = Math.max(0, Number(data.advanceDays) || 0);

        // Map and validate sections (for backward compatibility)
        let sections: DietPlanSection[] = [];
        if (data.sections && Array.isArray(data.sections)) {
            sections = data.sections.map((s: any) => new DietPlanSection(s.sequence, s.label, s.description || ''));
        }

        // Map schedule if provided
        let schedule: DietPlanDaySchedule[] = [];
        if (data.schedule && Array.isArray(data.schedule)) {
            schedule = data.schedule.map((d: any) => new DietPlanDaySchedule(
                d.dayIndex,
                d.date,
                d.month,
                d.week,
                d.dayOfWeek,
                d.label || `Day ${d.dayIndex}`,
                d.meals || {
                    breakfast: '',
                    midMorning: '',
                    lunch: '',
                    evening: '',
                    dinner: '',
                    water: '',
                    exercise: '',
                    notes: ''
                },
                d.notes || '',
                !!d.isCompleted
            ));
        }

        const dietPlan = new DietPlan(
            '', // ID will be generated by DB
            data.consultationId,
            data.customerId,
            durationType,
            durationValue,
            startDate, // originalStartDate
            startDate, // startDate
            sections,
            createdBy,
            new Date(),
            new Date(),
            durationMonths,
            endDate,
            visibilityDate,
            displayMode,
            advanceDays,
            !!data.repeatWeek,
            !!data.repeatMonth,
            schedule,
            []
        );

        return await this.dietPlanRepo.create(dietPlan);
    }
}
